// macOS — Big Sur style plate: 824 px rounded square on a 1024 grid, flat white, no shadow.
function macIconSVG(size) {
  const k = size / 1024;
  const plate = 824 * k, r = 185 * k, o = 100 * k;
  const m = size <= 64 ? MARK_SMALL : MARK;
  const h = plate * 0.68;
  const w = markWidth(h, m);
  return svgDoc(size, size,
    `<rect x="${fmt(o)}" y="${fmt(o)}" width="${fmt(plate)}" height="${fmt(plate)}" rx="${fmt(r)}" fill="${PALETTE.white}"/>
<rect x="${fmt(o + 0.5 * k * 4)}" y="${fmt(o + 0.5 * k * 4)}" width="${fmt(plate - k * 4)}" height="${fmt(plate - k * 4)}" rx="${fmt(r - k * 2)}" fill="none" stroke="${PALETTE.border}" stroke-width="${fmt(k * 4)}"/>
${mark({ x: (size - w) / 2, y: (size - h) / 2, h, m })}`, { title: 'Brizo macOS icon' });
}
out('icons/macos/brizo-macos-icon.svg', macIconSVG(1024), 'Source for the macOS plate icon');
const macPNG = new Map();
for (const s of [16, 32, 64, 128, 256, 512, 1024]) macPNG.set(s, renderPNG(macIconSVG(s), s).png);
out('icons/macos/brizo.icns', encodeICNS(ICNS_TYPES.map(([type, s]) => ({ type, png: macPNG.get(s) }))), 'PNG-payload ICNS, 16–1024 px incl. @2x');
for (const [name, s] of [['16x16', 16], ['16x16@2x', 32], ['32x32', 32], ['32x32@2x', 64], ['128x128', 128], ['128x128@2x', 256], ['256x256', 256], ['256x256@2x', 512], ['512x512', 512], ['512x512@2x', 1024]]) {
  out(`icons/macos/Brizo.iconset/icon_${name}.png`, macPNG.get(s), 'iconutil-compatible iconset');
}

