#!/usr/bin/env node
// Build every logo-derived Brizo asset from the master mark SVG.
//
//   node build-brand-assets.mjs [--source <dir>] [--out <dir>]
//
// Defaults: --source branding-private/source  --out branding-private/exports
//
// IMPORTANT: while logo provenance is unresolved (docs/BRAND_PROVENANCE.md) the
// output must stay outside tracked paths. The script refuses to write into the
// repository unless the target is git-ignored `branding-private/`.
import fs from 'node:fs';
import path from 'node:path';
import {
  PALETTE, REPO, renderPNG, textPath, write, fmt, svgBBox,
  encodeICO, encodeICNS, ICNS_TYPES, encodeBMP24,
} from './lib.mjs';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, arr) => (a.startsWith('--') ? [...acc, [a.slice(2), arr[i + 1]]] : acc), []),
);
const SRC = path.resolve(REPO, args.source ?? 'branding-private/source');
const OUT = path.resolve(REPO, args.out ?? 'branding-private/exports');

const rel = path.relative(REPO, OUT);
if (!rel.startsWith('..') && !rel.startsWith('branding-private')) {
  console.error(`Refusing to write logo-derived assets into tracked path "${rel}".`);
  console.error('Logo provenance is unresolved — see docs/BRAND_PROVENANCE.md.');
  process.exit(2);
}
for (const f of ['brizo-mark.svg', 'brizo-mark-small.svg']) {
  if (!fs.existsSync(path.join(SRC, f))) {
    console.error(`Missing master ${f} in ${SRC}. The logo master is kept privately; see docs/DEVELOPMENT_STATE.md.`);
    process.exit(1);
  }
}

// ---------------------------------------------------------------------------
// Load master geometry
// ---------------------------------------------------------------------------
function loadMark(file) {
  const svg = fs.readFileSync(path.join(SRC, file), 'utf8');
  const get = (id) => svg.match(new RegExp(`id="${id}"[^>]*\\sd="([^"]+)"`))[1];
  const paths = { rear: get('rear-sail'), front: get('front-sail'), hull: get('hull') };
  const inner = `<path d="${paths.rear}"/><path d="${paths.front}"/><path d="${paths.hull}"/>`;
  const bb = svgBBox(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="-200 -200 1200 1300">${inner}</svg>`);
  return { ...paths, bb };
}
const MARK = loadMark('brizo-mark.svg');
const MARK_SMALL = loadMark('brizo-mark-small.svg');

let uid = 0;
/**
 * Mark positioned so its bbox fits a box of `h` height whose top-left is (x, y).
 * mode: 'color' | 'mono' ; monoColor for mono.
 */
function mark({ x = 0, y = 0, h, m = MARK, mode = 'color', monoColor = PALETTE.text, gap = 14 }) {
  const s = h / m.bb.height;
  const t = `translate(${fmt(x - m.bb.x * s)} ${fmt(y - m.bb.y * s)}) scale(${fmt(s * 1e4) / 1e4})`;
  if (mode === 'color') {
    return `<g transform="${t}"><path fill="${PALETTE.lightSail}" d="${m.rear}"/><path fill="${PALETTE.primary}" d="${m.front}"/><path fill="${PALETTE.deepOcean}" d="${m.hull}"/></g>`;
  }
  // Monochrome: the front sail would merge with the rear sail, so a gap is
  // knocked out of the rear sail around the front sail.
  const id = `brizo-knockout-${++uid}`;
  return `<g transform="${t}"><mask id="${id}" maskUnits="userSpaceOnUse" x="-200" y="-200" width="1200" height="1300"><rect x="-200" y="-200" width="1200" height="1300" fill="#fff"/><path d="${m.front}" fill="#000" stroke="#000" stroke-width="${gap * 2}" stroke-linejoin="round"/></mask><g fill="${monoColor}"><path mask="url(#${id})" d="${m.rear}"/><path d="${m.front}"/><path d="${m.hull}"/></g></g>`;
}
const markWidth = (h, m = MARK) => (h / m.bb.height) * m.bb.width;

function svgDoc(w, h, body, { title = 'Brizo', bg } = {}) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/brand/build-brand-assets.mjs — PROVISIONAL candidate, do not publish (docs/BRAND_PROVENANCE.md). -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${fmt(w)} ${fmt(h)}" width="${fmt(w)}" height="${fmt(h)}">
<title>${title}</title>
${bg ? `<rect width="100%" height="100%" fill="${bg}"/>\n` : ''}${body}
</svg>
`;
}

const manifest = [];
function out(relPath, data, note = '') {
  write(path.join(OUT, relPath), data);
  manifest.push({ file: relPath, bytes: data.length, note });
}

// ---------------------------------------------------------------------------
// Wordmark — Inter SemiBold (OFL-1.1), outlined.
// ---------------------------------------------------------------------------
function wordmark(text, capH, color, weight = 600) {
  const probe = textPath(text, { weight, size: 100 });
  const size = (capH / probe.capHeight) * 100;
  const t = textPath(text, { weight, size, tracking: -size * 0.015 });
  return { width: t.width, capH, el: (x, baseline) => `<path fill="${color}" transform="translate(${fmt(x)} ${fmt(baseline)})" d="${t.d}"/>` };
}

// ---------------------------------------------------------------------------
// 1. Logo variants (SVG + PNG previews)
// ---------------------------------------------------------------------------
const PAD = 0.0625; // consistent 1/16 safe margin for square icons

function squareMark(size, { m = MARK, mode = 'color', monoColor, contentRatio = 1 - 2 * PAD } = {}) {
  const h = size * contentRatio;
  const w = markWidth(h, m);
  return mark({ x: (size - w) / 2, y: (size - h) / 2, h, m, mode, monoColor });
}

const S = 1024;
out('logo/brizo-mark.svg', svgDoc(S, S, squareMark(S), { title: 'Brizo mark' }), 'Primary mark, transparent, square artboard');
out('logo/brizo-mark-small.svg', svgDoc(S, S, squareMark(S, { m: MARK_SMALL }), { title: 'Brizo mark (small sizes)' }), 'Small-size optimized: wider sail/hull gap');
out('logo/brizo-mark-mono-dark.svg', svgDoc(S, S, squareMark(S, { mode: 'mono', monoColor: PALETTE.text })), 'Monochrome for light backgrounds');
out('logo/brizo-mark-mono-white.svg', svgDoc(S, S, squareMark(S, { mode: 'mono', monoColor: PALETTE.white })), 'Monochrome for dark backgrounds');
out('logo/brizo-mark-on-light.svg', svgDoc(S, S, squareMark(S), { bg: PALETTE.bgLight }), 'Mark on light background');
out('logo/brizo-mark-on-dark.svg', svgDoc(S, S, squareMark(S), { bg: PALETTE.bgDark }), 'Mark on dark background');

function horizontalLockup(text, { theme = 'light', mode = 'color' } = {}) {
  const H = 240; // mark height
  const color = theme === 'light' ? PALETTE.text : PALETTE.white;
  const wm = wordmark(text, H * 0.36, mode === 'mono' ? color : color);
  const mw = markWidth(H);
  const gap = H * 0.2;
  const pad = H * 0.25;
  const W = pad + mw + gap + wm.width + pad;
  const Ht = H + pad * 2;
  // Optical alignment: centre the cap height on the mark's vertical centre.
  const baseline = pad + H / 2 + wm.capH / 2;
  const body = mark({ x: pad, y: pad, h: H, mode, monoColor: color }) + '\n' + wm.el(pad + mw + gap, baseline);
  return svgDoc(W, Ht, body, { title: `${text} — horizontal lockup` });
}
function verticalLockup(text, { theme = 'light', mode = 'color' } = {}) {
  const H = 320;
  const color = theme === 'light' ? PALETTE.text : PALETTE.white;
  const wm = wordmark(text, H * 0.2, color);
  const mw = markWidth(H);
  const pad = H * 0.2;
  const gap = H * 0.16;
  const W = Math.max(mw, wm.width) + pad * 2;
  const Ht = pad + H + gap + wm.capH + pad;
  const body = mark({ x: (W - mw) / 2, y: pad, h: H, mode, monoColor: color }) + '\n' + wm.el((W - wm.width) / 2, pad + H + gap + wm.capH);
  return svgDoc(W, Ht, body, { title: `${text} — vertical lockup` });
}
for (const theme of ['light', 'dark']) {
  const on = theme === 'light' ? 'for light backgrounds' : 'for dark backgrounds';
  out(`logo/brizo-wordmark-${theme}.svg`, (() => {
    const wm = wordmark('Brizo', 120, theme === 'light' ? PALETTE.text : PALETTE.white);
    return svgDoc(wm.width + 40, 120 + 40, wm.el(20, 140), { title: 'Brizo wordmark' });
  })(), `Wordmark only, ${on}`);
  out(`logo/brizo-lockup-horizontal-${theme}.svg`, horizontalLockup('Brizo', { theme }), `Mark + wordmark, horizontal, ${on}`);
  out(`logo/brizo-lockup-vertical-${theme}.svg`, verticalLockup('Brizo', { theme }), `Mark + wordmark, vertical, ${on}`);
  out(`logo/brizo-browser-lockup-horizontal-${theme}.svg`, horizontalLockup('Brizo Browser', { theme }), `Product-name lockup, ${on}`);
  out(`logo/brizo-lockup-horizontal-mono-${theme}.svg`, horizontalLockup('Brizo', { theme, mode: 'mono' }), `Monochrome lockup, ${on}`);
  out(`logo/brizo-lockup-vertical-mono-${theme}.svg`, verticalLockup('Brizo', { theme, mode: 'mono' }), `Monochrome vertical lockup, ${on}`);
}

// ---------------------------------------------------------------------------
// 2. Transparent PNG ladder
// ---------------------------------------------------------------------------
const SIZES = [16, 24, 32, 48, 64, 128, 256, 512, 1024];
const SMALL_MAX = 32; // sizes <= this use the small-optimized mark
const pngCache = new Map();
function iconPNG(size, opts = {}) {
  const key = JSON.stringify([size, opts]);
  if (!pngCache.has(key)) {
    const m = size <= SMALL_MAX ? MARK_SMALL : MARK;
    pngCache.set(key, renderPNG(svgDoc(size, size, squareMark(size, { m, ...opts })), size).png);
  }
  return pngCache.get(key);
}
for (const s of SIZES) out(`png/brizo-mark-${s}.png`, iconPNG(s), s <= SMALL_MAX ? 'small-optimized geometry' : '');
for (const s of [32, 64, 256, 1024]) {
  out(`png/mono/brizo-mark-mono-dark-${s}.png`, iconPNG(s, { mode: 'mono', monoColor: PALETTE.text }));
  out(`png/mono/brizo-mark-mono-white-${s}.png`, iconPNG(s, { mode: 'mono', monoColor: PALETTE.white }));
}
for (const f of fs.readdirSync(path.join(OUT, 'logo')).filter((f) => f.endsWith('.svg') && !f.startsWith('brizo-mark'))) {
  const svg = fs.readFileSync(path.join(OUT, 'logo', f), 'utf8');
  const bg = f.includes('-dark') ? PALETTE.bgDark : undefined;
  out(`png/lockups/${f.replace('.svg', '.png')}`, renderPNG(svg, 1200, { background: bg }).png, bg ? 'preview on #0B1220' : 'transparent');
}

