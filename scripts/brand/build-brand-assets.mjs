  const fg = theme === 'light' ? PALETTE.text : PALETTE.white;
  const sub = theme === 'light' ? '#475569' : '#A9B8CC';
  const mh = 300, mw = markWidth(mh);
  const wm = wordmark('Brizo', 118, fg, 700);
  const tag = textPath('Fast. Private. Lightweight. Open.', { weight: 500, size: 38 });
  const st = textPath('EARLY DEVELOPMENT  ·  ARCHITECTURE & FOUNDATION', { weight: 600, size: 18, tracking: 1.2 });
  const left = 150, textX = left + mw + 80;
  const wave = (y, o, c) => `<path d="M0 ${y} C 213 ${y - 26}, 427 ${y + 26}, 640 ${y} S 1067 ${y - 26}, 1280 ${y} V 640 H 0 Z" fill="${c}" fill-opacity="${o}"/>`;
