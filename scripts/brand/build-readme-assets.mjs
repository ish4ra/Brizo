const BADGES = {
  status: ['status', 'early development', PALETTE.primary, PALETTE.white],
  phase: ['phase', '0 · foundation', PALETTE.deepOcean, PALETTE.white],
  licence: ['licence', 'pending decision', PALETTE.lightSail, PALETTE.text],
  targets: ['targets', 'Windows · macOS · Linux (planned)', '#475569', PALETTE.white],
};
function badge([label, value, bg, fg]) {
  const size = 11, H = 22, px = 8;
  const a = textPath(label, { size, weight: 600, tracking: 0.2 });
  const b = textPath(value, { size, weight: 600, tracking: 0.2 });
  const wa = a.width + px * 2, wb = b.width + px * 2, W = Math.ceil(wa + wb);
  const base = H / 2 + a.capHeight / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="${label}: ${value}">
<!-- Generated by scripts/brand/build-readme-assets.mjs — do not edit by hand. -->
<title>${label}: ${value}</title>
<clipPath id="r"><rect width="${W}" height="${H}" rx="5"/></clipPath>
<g clip-path="url(#r)"><rect width="${fmt(wa)}" height="${H}" fill="${PALETTE.text}"/><rect x="${fmt(wa)}" width="${fmt(W - wa)}" height="${H}" fill="${bg}"/></g>
<path fill="${PALETTE.white}" transform="translate(${px} ${fmt(base)})" d="${a.d}"/>
<path fill="${fg}" transform="translate(${fmt(wa + px)} ${fmt(base)})" d="${b.d}"/>
</svg>
`;
}

// --------------------------------------------------------------------------
// Appearance icons — 16 px sun and moon for the compact appearance note.
// One colour (Primary Blue) reads on both GitHub themes (3.7:1 / 4.7:1, above
// the 3:1 WCAG non-text minimum).
// --------------------------------------------------------------------------
const ICONS = {
  sun: (c) => {
    const rays = Array.from({ length: 8 }, (_, i) => {
      const a = (i * Math.PI) / 4, r1 = 5.4, r2 = 7.2;
      return `M${fmt(8 + r1 * Math.cos(a))} ${fmt(8 + r1 * Math.sin(a))}L${fmt(8 + r2 * Math.cos(a))} ${fmt(8 + r2 * Math.sin(a))}`;
    }).join('');
    return `<circle cx="8" cy="8" r="3.3" fill="${c}"/><path d="${rays}" stroke="${c}" stroke-width="1.5" stroke-linecap="round"/>`;
  },
  moon: (c) => `<path fill="${c}" d="M10.9 1.3A6.8 6.8 0 1 0 14.7 11 5.6 5.6 0 0 1 10.9 1.3Z"/>`,
};
function icon(name) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" role="img" aria-label="${name}">
<!-- Generated by scripts/brand/build-readme-assets.mjs — do not edit by hand. -->
<title>${name}</title>
${ICONS[name](PALETTE.primary)}
</svg>
`;
}

