export function main() {
// The public hero uses the temporary motif (D-013). hero() without a boat is
// the Task 001 wave-only hero, kept in history.
const builders = { hero: (t) => hero(t, { boat: MOTIF_BOAT }), divider, pillars, roadmap };
let n = 0;
for (const [name, fn] of Object.entries(builders)) {
  for (const theme of ['light', 'dark']) {
    const svg = fn(theme);
    write(path.join(OUT, `${name}-${theme}.svg`), svg);
    const W = Number(svg.match(/viewBox="0 0 (\d+)/)[1]);
    write(path.join(OUT, 'static', `${name}-${theme}.png`), renderPNG(svg, W).png);
    n += 2;
  }
}
for (const [k, def] of Object.entries(BADGES)) {
  const svg = badge(def);
  write(path.join(OUT, `badge-${k}.svg`), svg);
  const W = Number(svg.match(/viewBox="0 0 (\d+)/)[1]);
  write(path.join(OUT, 'static', `badge-${k}.png`), renderPNG(svg, W).png);
  n += 2;
}
for (const k of Object.keys(ICONS)) {
  const svg = icon(k);
  write(path.join(OUT, `icon-${k}.svg`), svg);
  write(path.join(OUT, 'static', `icon-${k}.png`), renderPNG(svg, 16).png);
  n += 2;
}
console.log(`Wrote ${n} README assets to ${path.relative(REPO, OUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
