#!/usr/bin/env node
// Generate the animated README artwork in assets/readme/.
//
//   node build-readme-assets.mjs
//
// All artwork here is SOURCE-INDEPENDENT (abstract waves, wind, course lines,
// typography). It deliberately contains no logo geometry while logo provenance
// is unresolved (docs/BRAND_PROVENANCE.md).
//
// GitHub renders README SVGs through <img>, which:
//   - never executes JavaScript  -> animation is pure CSS @keyframes;
//   - never loads web fonts      -> all text is outlined to paths (Inter, OFL);
//   - honours prefers-color-scheme via <picture> -> separate light/dark files;
//   - honours prefers-reduced-motion inside the SVG -> animations are disabled.
// Static PNG fallbacks (first frame) are rendered into assets/readme/static/.
import path from 'node:path';
import { PALETTE, REPO, renderPNG, textPath, write, fmt } from './lib.mjs';

const OUT = path.join(REPO, 'assets/readme');

const THEMES = {
  light: {
    bg: PALETTE.bgLight, card: PALETTE.white, border: PALETTE.border, text: PALETTE.text,
    muted: '#475569', accent: PALETTE.primary, accentText: PALETTE.deepOcean, faint: 0.35, track: '#C7D9EE',
  },
  dark: {
    bg: PALETTE.bgDark, card: '#111A2E', border: '#1E2B44', text: PALETTE.white,
    muted: '#A9B8CC', accent: PALETTE.primary, accentText: PALETTE.lightSail, faint: 0.22, track: '#24344F',
  },
};

// --------------------------------------------------------------------------
// Primitives
// --------------------------------------------------------------------------
function text(str, { x = 0, y = 0, size = 20, weight = 500, fill, tracking = 0, anchor = 'start', cls = '' }) {
  const t = textPath(str, { size, weight, tracking });
  const dx = anchor === 'middle' ? -t.width / 2 : anchor === 'end' ? -t.width : 0;
  return { el: `<path${cls ? ` class="${cls}"` : ''} fill="${fill}" transform="translate(${fmt(x + dx)} ${fmt(y)})" d="${t.d}"/>`, width: t.width };
}
function lines(arr, opts) {
  const lh = opts.lineHeight ?? opts.size * 1.45;
  return arr.map((s, i) => text(s, { ...opts, y: opts.y + i * lh }).el).join('');
}
function pill(label, { x, y, theme, anchor = 'start', size = 14 }) {
  const T = THEMES[theme];
  const t = textPath(label, { size, weight: 600, tracking: size * 0.08 });
  const w = t.width + size * 2, h = size * 2.1;
  const x0 = anchor === 'middle' ? x - w / 2 : x;
  return `<rect x="${fmt(x0)}" y="${fmt(y)}" width="${fmt(w)}" height="${fmt(h)}" rx="${fmt(h / 2)}" fill="${T.bg}"/>` +
    `<rect x="${fmt(x0)}" y="${fmt(y)}" width="${fmt(w)}" height="${fmt(h)}" rx="${fmt(h / 2)}" fill="${T.accent}" fill-opacity="${theme === 'light' ? 0.1 : 0.2}" stroke="${T.accent}" stroke-opacity="0.45"/>` +
    `<path fill="${T.accentText}" transform="translate(${fmt(x0 + size)} ${fmt(y + h / 2 + size * 0.36)})" d="${t.d}"/>`;
}

/** Periodic wave band: repeats every `period`, spans `width`, closed down to `bottom`. */
function waveBand({ y, amp, period, width, bottom }) {
  const q = period / 4;
  let d = `M0 ${fmt(y)}`;
  for (let x = 0; x < width; x += period) {
    d += ` C${fmt(x + q)} ${fmt(y - amp)} ${fmt(x + q)} ${fmt(y - amp)} ${fmt(x + 2 * q)} ${fmt(y)}`;
    d += ` C${fmt(x + 3 * q)} ${fmt(y + amp)} ${fmt(x + 3 * q)} ${fmt(y + amp)} ${fmt(x + period)} ${fmt(y)}`;
  }
  return `${d} V${fmt(bottom)} H0 Z`;
}
function waveLine({ y, amp, period, width }) {
  return waveBand({ y, amp, period, width, bottom: y }).replace(/ V.*$/, '');
}

const BASE_CSS = `
.drift{animation:drift linear infinite}
@keyframes drift{from{transform:translateX(0)}to{transform:translateX(var(--p))}}
.wind{stroke-dasharray:var(--l) 2000;stroke-dashoffset:var(--l);animation:wind 9s ease-in-out infinite;opacity:.0}
@keyframes wind{0%{stroke-dashoffset:var(--l);opacity:0}15%{opacity:.9}70%{opacity:.6}100%{stroke-dashoffset:-1400;opacity:0}}
.march{animation:march 2.4s linear infinite}
@keyframes march{to{stroke-dashoffset:-24}}
.pulse{transform-box:fill-box;transform-origin:center;animation:pulse 2.8s ease-out infinite}
@keyframes pulse{0%{transform:scale(.6);opacity:.7}100%{transform:scale(2.2);opacity:0}}
.breathe{animation:breathe 6s ease-in-out infinite}
@keyframes breathe{0%,100%{opacity:1}50%{opacity:.55}}
@media (prefers-reduced-motion:reduce){*{animation:none!important}.wind{opacity:.5;stroke-dasharray:none}}
`;

function svgDoc(w, h, css, body, { title, desc }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-labelledby="t d">
<!-- Generated by scripts/brand/build-readme-assets.mjs — do not edit by hand. -->
<title id="t">${title}</title><desc id="d">${desc}</desc>
<style>${BASE_CSS}${css}</style>
${body}
</svg>
`;
}

// --------------------------------------------------------------------------
// Hero banner
// --------------------------------------------------------------------------
function hero(theme) {
  const T = THEMES[theme];
  const W = 1280, H = 460;
  const clip = `<clipPath id="frame"><rect x="1" y="1" width="${W - 2}" height="${H - 2}" rx="28"/></clipPath>`;
  const bands = [
    { y: 372, amp: 10, period: 640, c: PALETTE.lightSail, o: T.faint + 0.1, dur: 26 },
    { y: 392, amp: 12, period: 800, c: PALETTE.primary, o: theme === 'light' ? 0.55 : 0.6, dur: 19 },
    { y: 414, amp: 9, period: 560, c: PALETTE.deepOcean, o: 1, dur: 14 },
  ].map((b, i) => `<g class="drift" style="--p:-${b.period}px;animation-duration:${b.dur}s"><path fill="${b.c}" fill-opacity="${b.o}" d="${waveBand({ y: b.y, amp: b.amp, period: b.period, width: W + b.period, bottom: H })}"/></g>`).join('\n');

  const winds = [
    { d: 'M-40 118 C 180 92, 360 140, 600 108 S 980 84, 1320 118', l: 260, delay: 0 },
    { d: 'M-40 188 C 220 170, 420 206, 700 182 S 1060 164, 1320 190', l: 200, delay: 3 },
    { d: 'M-40 262 C 160 250, 380 280, 640 258 S 1000 240, 1320 268', l: 320, delay: 5.5 },
  ].map((w) => `<path class="wind" style="--l:${w.l};animation-delay:${w.delay}s" d="${w.d}" fill="none" stroke="${PALETTE.lightSail}" stroke-width="2" stroke-linecap="round"/>`).join('\n');

  // Navigation course: dashed arc from left to right with a pulsing waypoint.
  const course = `<path class="march" d="M120 330 C 330 250, 520 300, 640 300 S 1000 240, 1160 300" fill="none" stroke="${T.accent}" stroke-opacity=".55" stroke-width="2" stroke-dasharray="2 10" stroke-linecap="round"/>
<circle cx="1160" cy="300" r="7" fill="${T.accent}"/><circle class="pulse" cx="1160" cy="300" r="7" fill="none" stroke="${T.accent}" stroke-width="2"/>
<circle cx="120" cy="330" r="5" fill="${T.accent}" fill-opacity=".6"/>`;

  const title = text('Brizo', { x: W / 2, y: 196, size: 132, weight: 700, fill: T.text, anchor: 'middle', tracking: -3 }).el;
  const tag = text('Fast. Private. Lightweight. Open.', { x: W / 2, y: 250, size: 30, weight: 500, fill: T.muted, anchor: 'middle' }).el;
  const status = pill('EARLY DEVELOPMENT  ·  ARCHITECTURE & FOUNDATION', { x: W / 2, y: 280, theme, anchor: 'middle', size: 15 });

  return svgDoc(W, H, '', `<defs>${clip}</defs>
<g clip-path="url(#frame)">
<rect width="${W}" height="${H}" fill="${T.bg}"/>
${winds}
${course}
${bands}
</g>
<rect x="1" y="1" width="${W - 2}" height="${H - 2}" rx="28" fill="none" stroke="${T.border}" stroke-width="2"/>
${title}
${tag}
${status}`, {
    title: 'Brizo — Fast. Private. Lightweight. Open.',
    desc: 'Brizo browser banner: wordmark and tagline over gently moving ocean waves and wind lines. Status: early development, architecture and foundation.',
  });
}

// --------------------------------------------------------------------------
// Divider
// --------------------------------------------------------------------------
function divider(theme) {
  const T = THEMES[theme];
  const W = 1280, H = 28;
  return svgDoc(W, H, '', `<g class="drift" style="--p:-160px;animation-duration:8s">
<path d="${waveLine({ y: 14, amp: 5, period: 160, width: W + 160 })}" fill="none" stroke="${T.track}" stroke-width="2"/>
</g>
<g class="drift" style="--p:-160px;animation-duration:8s"><path class="breathe" d="${waveLine({ y: 14, amp: 5, period: 160, width: W + 160 })}" fill="none" stroke="${PALETTE.primary}" stroke-width="2" stroke-dasharray="80 400" stroke-linecap="round"/></g>`,
  { title: 'Section divider', desc: 'A thin animated wave line.' });
}

